#!/usr/bin/env bash
# Prepare (but do NOT send) a Telegraph eval-pool truth-source submission.
#
#   ./prepare-submission.sh <truth-source.yaml>
#
# Writes, into ./build/:
#   items.jsonl      the exact request body (one JSON row)
#   message.txt      the exact EIP-191 message that will be signed
#   body.sha256      the body hash
#   nonce.txt        a fresh 8-128 char nonce
#   upload.sh        the ready-to-run curl (placeholders filled from the above)
#
# It computes the body hash, the nonce and the canonical message, and prints
# them. It does NOT sign and does NOT upload.
#
# The private key is never read, printed, or passed on a command line by this
# script. Signing is a separate step you run yourself.
set -euo pipefail

YAML_FILE="${1:?usage: prepare-submission.sh <truth-source.yaml>}"
INTENT="DNS_RECORD_LOOKUP_GENERAL"
NODE="https://devnode.telegraphprotocol.com"
CHAIN_ID=11155111   # Ethereum Sepolia, per the docs
OUT="$(cd "$(dirname "$0")" && pwd)/build"

[ -f "$YAML_FILE" ] || { echo "no such file: $YAML_FILE" >&2; exit 1; }
mkdir -p "$OUT"

echo "== 1. build the JSONL body (one truth_source row) =="
# jq does the JSON string escaping of the YAML document.
jq -Rsc '{label_kind: "truth_source", source: .}' "$YAML_FILE" > "$OUT/items.jsonl"
echo "   wrote $OUT/items.jsonl"
echo "   rows: $(wc -l < "$OUT/items.jsonl" | tr -d ' ')"
echo "   bytes: $(wc -c < "$OUT/items.jsonl" | tr -d ' ')"

echo
echo "== 2. body sha256 (over the EXACT bytes that will be sent) =="
BODY_SHA="$(sha256sum "$OUT/items.jsonl" | cut -d' ' -f1)"
printf '%s' "$BODY_SHA" > "$OUT/body.sha256"
echo "   $BODY_SHA"

echo
echo "== 3. fresh nonce (8 to 128 chars, one use per signer) =="
NONCE="$(openssl rand -hex 16)"
printf '%s' "$NONCE" > "$OUT/nonce.txt"
echo "   $NONCE (${#NONCE} chars)"

echo
echo "== 4. the canonical EIP-191 message (five lines, NO trailing newline) =="
MSG="$(printf 'Telegraph eval-pool submission v1\nintent_id: %s\nbody_sha256: %s\nnonce: %s\nchain_id: %s' \
  "$INTENT" "$BODY_SHA" "$NONCE" "$CHAIN_ID")"
printf '%s' "$MSG" > "$OUT/message.txt"
echo "----8<----"
printf '%s\n' "$MSG"
echo "---->8----"
echo "   bytes: $(wc -c < "$OUT/message.txt" | tr -d ' ')  (no trailing newline)"
echo "   lines: $(wc -l < "$OUT/message.txt" | tr -d ' ')"
echo "   last byte is newline: $(tail -c1 "$OUT/message.txt" | od -An -c | grep -q '\\n' && echo yes || echo no)"

echo
echo "== 5. the curl that would POST it (signature placeholder unfilled) =="
cat > "$OUT/upload.sh" <<EOF
#!/usr/bin/env bash
# Generated by prepare-submission.sh. Fill SIG, then run.
set -euo pipefail
SIG="<65-byte-hex-EIP-191-signature>"
NONCE="\$(cat "$OUT/nonce.txt")"
curl -s -X POST "$NODE/api/evalpool/submissions?intent_id=$INTENT&submitter=\$ADDR" \\
  -H "Content-Type: application/x-ndjson" \\
  -H "X-Evalpool-Signature: \$SIG" \\
  -H "X-Evalpool-Nonce: \$NONCE" \\
  --data-binary @"$OUT/items.jsonl"
EOF
chmod +x "$OUT/upload.sh"
cat "$OUT/upload.sh"

echo
echo "Prepared. Nothing was signed and nothing was uploaded."
echo "Artifacts in $OUT"
